#!/usr/bin/env python3
"""Guarded native Linux execution of embedded tensor repacking, NOT inference.

Only the pinned SM89 GPU module runs; the Windows DLL is read as data. The CPU
reference expresses an experimentally validated tiled-layout interpretation,
not a fully recovered ABI or GPU instruction proof. No model weights, GPU module
images or disassembly are deliberately written to files. Core dumps are disabled;
swap/driver persistence and memory erasure are not controlled.
"""
from __future__ import annotations

import argparse
from contextlib import ExitStack
import ctypes as ct
import importlib.util
import json
from pathlib import Path
from typing import Any

spec = importlib.util.spec_from_file_location("native_utility", Path(__file__).with_name("native-kernel-probe.py"))
if spec is None or spec.loader is None:
    raise RuntimeError("missing utility probe module")
utility = importlib.util.module_from_spec(spec)
spec.loader.exec_module(utility)
base = utility.base

GUARD_WORDS = 256  # Preserve 1024-byte alignment of the active device addresses.
SIZES = ((4, 4), (4, 8), (8, 4), (8, 8), (12, 8), (16, 12))
# Literal known answers: (height, width, y, x, channel_pair, 2D word, 1D word).
# Independently enumerated logical-token examples; never generated by mapping()
# or within_tile(). See NATIVE-TENSOR.md for the behavioural derivation.
KNOWN_ANSWERS = ((4, 8, 0, 4, 0, 8192, 64),
                 (4, 8, 2, 1, 5, 23, 8214),
                 (8, 8, 1, 4, 8, 8384, 193),
                 (12, 8, 8, 5, 511, 49054, 40926),
                 (16, 12, 5, 9, 4, 41042, 32850))


class RepackArguments(ct.Structure):
    _fields_ = [("source", ct.c_uint64), ("destination", ct.c_uint64),
                ("height", ct.c_int32), ("width", ct.c_int32)]


def tensor_words(height: int, width: int) -> int:
    base.require(4 <= height <= 64 and 4 <= width <= 64 and height % 4 == 0 and width % 4 == 0,
                 "probe only supports positive complete 4x4 tiles, dimensions <=64")
    return height * width * 512


def within_tile(spatial: int, channel_pair: int) -> int:
    """Inferred layout: 16 positions x 512 uint32 words (likely FP16 pairs).

    Groups of eight channel pairs occupy 128 words, with the two halves of the
    spatial tile and channel group interleaved in the low four address bits.
    """
    return ((channel_pair // 8) * 128 + (spatial // 8) + ((channel_pair // 4) % 2) * 2
            + (spatial % 8) * 16 + (channel_pair % 4) * 4)


def mapping(height: int, width: int) -> list[tuple[int, int]]:
    """Return (2D tiled index, 1D tiled index), in logical token/channel order."""
    count = tensor_words(height, width)
    indices = []
    for token in range(height * width):
        y, x = divmod(token, width)
        tile = (y // 4) * (width // 4) + x // 4
        spatial = (y % 4) * 4 + x % 4
        for channel in range(512):
            indices.append((tile * 8192 + within_tile(spatial, channel),
                            (token // 16) * 8192 + within_tile(token % 16, channel)))
    # Range and bijection checked before device allocation or launch.
    base.require(len(indices) == count and sorted(i for i, _ in indices) == list(range(count))
                 and sorted(i for _, i in indices) == list(range(count)), "non-bijective tensor layout")
    return indices


def reference(source: list[int], indices: list[tuple[int, int]], inverse: bool) -> list[int]:
    base.require(len(source) == len(indices), "reference tensor size mismatch")
    output = [0] * len(source)
    for tiled_2d, tiled_1d in indices:
        src, dst = (tiled_1d, tiled_2d) if inverse else (tiled_2d, tiled_1d)
        output[dst] = source[src]
    return output


def pattern(count: int, seed: int) -> list[int]:
    # Odd multiplication is a bijection modulo 2^32, exposing index permutations
    # and retaining arbitrary FP16 bit patterns without numerical conversion.
    return [(((i * 0x9E3779B1) & 0xFFFFFFFF) ^ seed) for i in range(count)]


def exact(label: str, actual: list[int], expected: list[int]) -> dict[str, Any]:
    if len(actual) != len(expected):
        raise utility.OutputMismatch(f"{label}: length mismatch")
    for i, (a, e) in enumerate(zip(actual, expected)):
        if a != e:
            raise utility.OutputMismatch(f"{label}: word {i}: {a:#x} != {e:#x}")
    return dict(operation=label, checked_words=len(expected), bit_exact=True)


def known_answer_test() -> dict[str, Any]:
    checked = rejected = 0
    for height, width, y, x, channel, tiled_2d, tiled_1d in KNOWN_ANSWERS:
        indices = mapping(height, width)
        logical = (y * width + x) * 512 + channel
        base.require(tiled_2d != tiled_1d, "known answer must expose a non-identity permutation")
        exact("logical-token-known-answer", list(indices[logical]), [tiled_2d, tiled_1d])
        source = pattern(len(indices), 0x12345678)
        forward = reference(source, indices, False)
        backward = reference(source, indices, True)
        exact("forward-known-answer", [forward[tiled_1d]], [source[tiled_2d]])
        exact("inverse-known-answer", [backward[tiled_2d]], [source[tiled_1d]])
        checked += 2
        # Controls use the real tensor reference, not an unrelated [1, 2] test.
        controls = [("wrong-reference-identity", source[tiled_1d]),
                    ("wrong-orientation", backward[tiled_1d]),
                    # Swapped pointers leave the designated poisoned destination
                    # unchanged; model that observation without an unsafe launch.
                    ("wrong-pointer-fields", source[tiled_2d] ^ 0xFFFFFFFF)]
        if height != width:
            swapped = reference(source, mapping(width, height), False)
            controls.append(("wrong-dimension-fields", swapped[tiled_1d]))
        for label, value in controls:
            try:
                exact(label, [value], [source[tiled_2d]])
            except utility.OutputMismatch:
                rejected += 1
            else:
                raise ValueError(f"{label} control was accepted")
    return dict(known_answer_pairs=len(KNOWN_ANSWERS), known_answer_words=checked,
                known_answer_negative_controls_rejected=rejected)


def self_test() -> dict[str, Any]:
    # Host packing only: SM89 metadata exposes one opaque 24-byte parameter,
    # not these internal field names, offsets or meanings.
    base.require(ct.sizeof(RepackArguments) == 24 and RepackArguments.source.offset == 0
                 and RepackArguments.destination.offset == 8 and RepackArguments.height.offset == 16
                 and RepackArguments.width.offset == 20, "repack host ABI mismatch")
    known_answers = known_answer_test()
    checked = 0
    non_identity = 0
    for height, width in SIZES:
        indices = mapping(height, width)
        source = pattern(len(indices), 0x12345678)
        transformed = reference(source, indices, False)
        exact("cpu-round-trip", reference(transformed, indices, True), source)
        checked += len(indices)
        non_identity += int(transformed != source)
    base.require(non_identity == 4, "test shapes do not expose the intended tile permutation")
    for dimensions in ((0, 4), (-4, 4), (4, 3), (6, 8), (68, 4)):
        try:
            tensor_words(*dimensions)
        except ValueError:
            continue
        raise ValueError("invalid dimensions accepted")
    # Tensor-specific wrong-reference controls are checked above.
    # Distinct allocation guards expose a surplus identity-layout copy that the
    # former identical canaries could conceal. They cannot detect read-only OOB.
    source_guard = pattern(GUARD_WORDS, 0xCAFE0001)
    destination_guard = pattern(GUARD_WORDS, 0x13570003)
    try:
        exact("copied-source-guard", source_guard, destination_guard)
    except utility.OutputMismatch:
        pass
    else:
        raise ValueError("cross-allocation guard copy was accepted")
    return dict(**known_answers, cross_allocation_guard_copy_rejected=True,
                cpu_layout_checked_words=checked, shapes=len(SIZES),
                non_identity_shapes=non_identity, invalid_shapes_rejected=True,
                wrong_reference_rejected=True)


def execute(data: bytes, inventory: dict[str, Any], skip: bool) -> dict[str, Any]:
    cpu_checks = self_test()
    driver = utility.Driver()
    device, version = utility.select_device(driver)
    checks: list[dict[str, Any]] = []
    launches = readbacks = 0
    rejection = ""
    with ExitStack() as stack:
        context = ct.c_void_p()
        driver.check("cuCtxCreate_v2", ct.byref(context), 0, device)
        stack.callback(driver.check, "cuCtxDestroy_v2", context)
        base.require(bool(context.value), "null CUDA context")
        entry = next(e for e in inventory["fatbins"][5]["entries"] if e["kind"] == 2 and e["arch"] == 89)
        image = base.decompress(data, entry)
        module = ct.c_void_p()
        driver.check("cuModuleLoadData", ct.byref(module), ct.create_string_buffer(image))
        stack.callback(driver.check, "cuModuleUnload", module)
        base.require(bool(module.value), "null CUDA module")
        functions = []
        for name in ("cc_vit_1d_repack_2d_to_1d", "cc_vit_1d_repack_1d_to_2d"):
            # One opaque 24-byte argument only; internal fields are empirical.
            utility.verify_kernel_abi(image, name, 24)
            function = ct.c_void_p()
            driver.check("cuModuleGetFunction", ct.byref(function), module, name.encode("ascii"))
            base.require(bool(function.value), "null CUDA function")
            functions.append(function)

        for height, width in SIZES:
            indices = mapping(height, width)
            count = len(indices)
            for seed in (0x12345678, 0xA5C30F17):
                # Each kernel is independently validated; this is not merely a round trip.
                for inverse, function in enumerate(functions):
                    values = pattern(count, seed)
                    expected = reference(values, indices, bool(inverse))
                    poison = [value ^ 0xFFFFFFFF for value in expected]
                    source_pre = pattern(GUARD_WORDS, seed ^ 0xCAFE0001)
                    source_post = pattern(GUARD_WORDS, seed ^ 0xBAAD0002)
                    destination_pre = pattern(GUARD_WORDS, seed ^ 0x13570003)
                    destination_post = pattern(GUARD_WORDS, seed ^ 0x24680004)
                    source_values = source_pre + values + source_post
                    destination_values = destination_pre + poison + destination_post
                    expected_destination = destination_pre + expected + destination_post
                    array_type = ct.c_uint32 * len(source_values)
                    with ExitStack() as allocations:
                        pointers = []
                        for uploaded in (source_values, destination_values):
                            pointer = ct.c_uint64()
                            driver.check("cuMemAlloc_v2", ct.byref(pointer), ct.sizeof(array_type))
                            allocations.callback(driver.check, "cuMemFree_v2", pointer)
                            base.require(pointer.value != 0, "null device allocation")
                            driver.check("cuMemcpyHtoD_v2", pointer, array_type(*uploaded), ct.sizeof(array_type))
                            pointers.append(pointer)
                        args = RepackArguments(pointers[0].value + GUARD_WORDS * 4,
                                               pointers[1].value + GUARD_WORDS * 4, height, width)
                        if not skip:
                            arguments = (ct.c_void_p * 1)(ct.addressof(args))
                            # One deliberately extra block exercises the empirically observed count guard.
                            driver.check("cuLaunchKernel", function, (count + 255) // 256 + 1, 1, 1,
                                         256, 1, 1, 0, None, arguments, None)
                            launches += 1
                            driver.check("cuCtxSynchronize")
                        actual = []
                        for pointer in pointers:
                            host = array_type()
                            driver.check("cuMemcpyDtoH_v2", host, pointer, ct.sizeof(array_type))
                            readbacks += 1
                            actual.append(list(host))
                        label = f"{'1d-to-2d' if inverse else '2d-to-1d'}-{height}x{width}-{seed:08x}"
                        checks.append(exact(label + "-source-and-guards", actual[0], source_values))
                        if skip:
                            checks.append(exact(label + "-untouched-destination-and-guards", actual[1], destination_values))
                            try:
                                exact(label, actual[1], expected_destination)
                            except utility.OutputMismatch as error:
                                rejection = str(error)
                            base.require(bool(rejection), "skipped repack unexpectedly passed")
                        else:
                            checks.append(exact(label + "-destination-and-guards", actual[1], expected_destination))
                    if skip:
                        break
                if skip:
                    break
            if skip:
                break
        driver.check("cuCtxSynchronize")
    return dict(native=True, driver_api_version=version, device="NVIDIA GeForce RTX 4070 Ti SUPER",
                cpu_checks=cpu_checks, kernels_launched=launches, readbacks=readbacks,
                checks=checks, skipped_repack=skip, skipped_repack_rejected=bool(rejection),
                rejection=rejection, context_destroyed=True, resources_destroyed=True,
                evaluations=0, weights_used=False, weight_files_written=False, module_image_files_written=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("self-test", "execute", "skip-repack"))
    parser.add_argument("dll", nargs="?", type=Path)
    args = parser.parse_args()
    if args.mode == "self-test":
        print(json.dumps(self_test(), indent=2))
        return
    base.require(args.dll is not None, "DLL path required for native execution")
    protection = base.protect_process_memory()
    data = base.read_bounded(args.dll)
    report = execute(data, base.inventory(data), args.mode == "skip-repack")
    print(json.dumps(dict(sha256=base.PIN, memory_protection=protection, cuda=report), indent=2))


if __name__ == "__main__":
    main()
